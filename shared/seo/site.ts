/**
 * Turns a site path into an absolute URL on the canonical origin. The home
 * page keeps its trailing slash ("https://host/"); every other path is
 * returned without one, matching the URLs the site actually serves.
 */
export function absoluteUrl(path = "/"): string {
  if (/^https?:\/\//i.test(path)) {
    return path;
  }

  const normalized = `/${path.replace(/^\/+/, "")}`;

  if (normalized === "/") {
    return `${SITE_URL}/`;
  }

  return `${SITE_URL}${normalized.replace(/\/+$/, "")}`;
}
